import pandas as pd

hosp = pd.read_csv('hospitals_doctors_india.csv')
print('=== Hospitals & Doctors ===')
print('Rows:', len(hosp))
print('Unique Hospitals:', hosp['HospitalID'].nunique())
print('Cities:', hosp['City'].unique())
print('States:', hosp['State'].unique())
print('Types:', hosp['Type'].value_counts().to_dict())
hosp_unique = hosp.drop_duplicates(subset=['HospitalID'])
print('Total Beds:', hosp_unique['Beds'].sum())
print('Total ICU Beds:', hosp_unique['ICU_Beds'].sum())
print('Total Ventilators:', hosp_unique['Ventilators'].sum())
print('Doctors count:', hosp['DoctorID'].nunique())
print('Specializations:', hosp['Specialization'].value_counts().to_dict())

pharma = pd.read_csv('pharma_sales.csv')
print('\n=== Pharma Sales & Inventory ===')
print('Rows:', len(pharma))
print('Unique Drugs:', pharma['Drug_Name'].unique())
print('Categories:', pharma['Category'].unique())
print('Regions:', pharma['Region'].unique())
print('Expired count:', (pharma['Expired_Stock'] == 'Yes').sum())
print('Negative or low expiry days (<= 30):', (pharma['Expiry_Days_Left'] <= 30).sum())
print('Distributors:', pharma['Distributor'].unique())
print('Summary stats for Quantity:')
print(pharma['Quantity'].describe())
